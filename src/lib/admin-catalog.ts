import "server-only";

import { and, eq, sql } from "drizzle-orm";

import { db } from "@/db";
import { products, productStock } from "@/db/schema";
import { pgError } from "./pg-error";
import type { ProductField, ProductInput } from "./product-input";
import { FEATURED_SLUG } from "./product-queries";
import type { StockInput } from "./stock-input";

// Admin catalog writes. Inputs are already parsed by parseProductForm; this
// layer owns the database rules. No authorization happens in here: only call it
// from Server Actions, after requireAdmin (`pnpm check:admin` blocks imports from
// anywhere else). The Neon HTTP driver has no interactive transactions, so each
// multi-statement write is one db.batch (a single transaction).

type Batch = Parameters<typeof db.batch>[0];

export type WriteFailure = { ok: false; field?: ProductField; message: string };

/** Maps the constraint a failed write tripped to a message for the admin. */
function writeFailure(error: unknown): WriteFailure {
  const { code, constraint } = pgError(error);
  if (code === "23505" && constraint === "products_slug_unique") {
    return { ok: false, field: "slug", message: "Another product already uses this slug." };
  }
  if (code === "23505" && constraint === "products_reference_unique") {
    return { ok: false, field: "reference", message: "Another product already uses this reference." };
  }
  if (code === "23503" && constraint === "products_category_id_categories_id_fk") {
    return { ok: false, field: "categoryId", message: "That category no longer exists." };
  }
  throw error;
}

function fields(input: ProductInput) {
  return {
    categoryId: input.categoryId,
    reference: input.reference,
    name: input.name,
    priceCents: input.priceCents,
    badge: input.badge,
    description: input.description,
    details: input.details,
    colors: input.colors,
    images: input.images,
  };
}

/** Creates the product and its stock rows together, so it is never saleable half made. */
export async function createProduct(
  input: ProductInput,
): Promise<{ ok: true; id: number } | WriteFailure> {
  // Row ids are generated by the database, so stock points at the product by its slug.
  const productId = sql<number>`(select id from ${products} where ${products.slug} = ${input.slug})`;

  try {
    await db.batch([
      db.insert(products).values({ slug: input.slug, ...fields(input) }),
      db.insert(productStock).values(
        input.sizes.map((size, position) => ({
          productId,
          size: size.label,
          quantity: size.quantity,
          position,
        })),
      ),
    ] as unknown as Batch);
  } catch (error) {
    return writeFailure(error);
  }

  const [row] = await db
    .select({ id: products.id })
    .from(products)
    .where(eq(products.slug, input.slug));
  return { ok: true, id: row.id };
}

/**
 * Updates a product's details, category and price, and appends any new sizes.
 * The slug is never written. Existing stock rows are never touched here, because
 * checkouts change them concurrently (stock has its own compare-and-set update).
 */
export async function updateProduct(
  id: number,
  input: ProductInput,
  nextPosition: number,
): Promise<{ ok: true } | WriteFailure> {
  const statements: unknown[] = [db.update(products).set(fields(input)).where(eq(products.id, id))];
  if (input.sizes.length > 0) {
    statements.push(
      db
        .insert(productStock)
        .values(
          input.sizes.map((size, index) => ({
            productId: id,
            size: size.label,
            quantity: size.quantity,
            position: nextPosition + index,
          })),
        )
        .onConflictDoNothing(),
    );
  }

  try {
    await db.batch(statements as unknown as Batch);
  } catch (error) {
    return writeFailure(error);
  }
  return { ok: true };
}

export type StockWrite =
  | { ok: true }
  | { ok: false; reason: "missing" }
  | { ok: false; reason: "changed"; current: number };

/**
 * Sets a size's quantity, but only if it still holds the value the admin was
 * looking at. Checkouts reserve and release units with relative updates at any
 * moment, so a blind overwrite from a stale page would silently undo them. One
 * statement, so the compare and the write are atomic; when a checkout commits
 * first the row no longer matches and nothing is written.
 */
export async function setStockQuantity(input: StockInput): Promise<StockWrite> {
  const where = and(eq(productStock.productId, input.productId), eq(productStock.size, input.size));

  const updated = await db
    .update(productStock)
    .set({ quantity: input.quantity })
    .where(and(where, eq(productStock.quantity, input.expected)))
    .returning({ quantity: productStock.quantity });
  if (updated.length > 0) return { ok: true };

  const [row] = await db.select({ quantity: productStock.quantity }).from(productStock).where(where);
  return row ? { ok: false, reason: "changed", current: row.quantity } : { ok: false, reason: "missing" };
}

/** Hides a product from the storefront (or shows it again). Rows are never deleted. */
export async function setProductArchived(
  id: number,
  archived: boolean,
): Promise<{ ok: true } | { ok: false; message: string }> {
  const [row] = await db
    .select({ slug: products.slug })
    .from(products)
    .where(eq(products.id, id));
  if (!row) return { ok: false, message: "This product no longer exists." };
  if (archived && row.slug === FEATURED_SLUG) {
    return { ok: false, message: "This product is featured on the home page and cannot be hidden." };
  }

  await db
    .update(products)
    .set({
      // Hiding twice keeps the first timestamp.
      archivedAt: archived ? sql`coalesce(${products.archivedAt}, now())` : null,
    })
    .where(eq(products.id, id));
  return { ok: true };
}

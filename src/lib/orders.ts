import "server-only";

import { randomUUID } from "node:crypto";

import { and, desc, eq, inArray, isNull, sql } from "drizzle-orm";

import { db } from "@/db";
import {
  orderItems,
  orders,
  productStock,
  stripeEvents,
  type ShippingAddress,
} from "@/db/schema";
import { CURRENCY } from "./checkout-config";

// Order persistence. Everything here is database-only (no Stripe, no Next
// caches) so the state transitions can be exercised on their own. The Neon HTTP
// driver has no interactive transactions, so atomicity comes from db.batch()
// (one transaction), single statements, and the CHECK constraints on the tables.
//
// Money in here always comes from the priced cart (database prices) or from the
// order row itself, never from the browser.

export type OrderItemInput = {
  productId: number;
  slug: string;
  reference: string;
  name: string;
  size: string;
  color: string | null;
  unitPriceCents: number;
  quantity: number;
};

function pgError(error: unknown): { code?: string; constraint?: string } {
  // Drizzle wraps driver errors, keeping the original in `cause`.
  let current: unknown = error;
  for (let depth = 0; depth < 3 && typeof current === "object" && current; depth++) {
    const { code, constraint, cause } = current as Record<string, unknown>;
    if (typeof code === "string") {
      return {
        code,
        constraint: typeof constraint === "string" ? constraint : undefined,
      };
    }
    current = cause;
  }
  return {};
}

/** Units to take off (or put back on) the shelf, one entry per product and size. */
function stockUse(items: Pick<OrderItemInput, "productId" | "size" | "quantity">[]) {
  const use = new Map<string, { productId: number; size: string; quantity: number }>();
  for (const item of items) {
    const key = `${item.productId}:${item.size}`;
    const entry = use.get(key) ?? { productId: item.productId, size: item.size, quantity: 0 };
    entry.quantity += item.quantity;
    use.set(key, entry);
  }
  return [...use.values()];
}

function takeStock(use: ReturnType<typeof stockUse>) {
  return use.map(({ productId, size, quantity }) =>
    db
      .update(productStock)
      .set({ quantity: sql`${productStock.quantity} - ${quantity}` })
      .where(and(eq(productStock.productId, productId), eq(productStock.size, size))),
  );
}

type Batch = Parameters<typeof db.batch>[0];

/* Reserving -------------------------------------------------------------- */

export type ReserveResult =
  | { ok: true; id: number; publicId: string }
  | { ok: false; reason: "stock" | "busy" };

/**
 * Creates a pending order and takes its units off the shelf in one atomic
 * batch. If any size has too little left, product_stock's quantity >= 0 check
 * fails and the whole batch rolls back, so stock can never be oversold.
 */
export async function reserveOrder(input: {
  userId: string;
  items: OrderItemInput[];
  shippingCents: number;
  reservedUntil: Date;
}): Promise<ReserveResult> {
  const { userId, items, shippingCents, reservedUntil } = input;
  if (items.length === 0) return { ok: false, reason: "stock" };

  const publicId = randomUUID();
  const subtotalCents = items.reduce((sum, i) => sum + i.unitPriceCents * i.quantity, 0);
  // Row ids are generated by the database, so lines point at the order by its public id.
  const orderId = sql<number>`(select id from ${orders} where ${orders.publicId} = ${publicId})`;

  const statements = [
    db.insert(orders).values({
      publicId,
      userId,
      currency: CURRENCY,
      subtotalCents,
      shippingCents,
      totalCents: subtotalCents + shippingCents,
      reservedUntil,
    }),
    db.insert(orderItems).values(
      items.map((item) => ({
        orderId,
        productId: item.productId,
        productSlug: item.slug,
        reference: item.reference,
        name: item.name,
        size: item.size,
        color: item.color,
        unitPriceCents: item.unitPriceCents,
        quantity: item.quantity,
      })),
    ),
    ...takeStock(stockUse(items)),
  ];

  try {
    await db.batch(statements as unknown as Batch);
  } catch (error) {
    const { code, constraint } = pgError(error);
    if (code === "23514" && constraint === "product_stock_quantity_non_negative") {
      return { ok: false, reason: "stock" };
    }
    if (code === "23505" && constraint === "orders_one_pending_per_user_idx") {
      return { ok: false, reason: "busy" };
    }
    throw error;
  }

  const [row] = await db
    .select({ id: orders.id })
    .from(orders)
    .where(eq(orders.publicId, publicId));
  return { ok: true, id: row.id, publicId };
}

/** Records the Stripe Checkout Session on an order that does not have one yet. */
export async function attachCheckoutSession(publicId: string, sessionId: string) {
  await db
    .update(orders)
    .set({ stripeCheckoutSessionId: sessionId })
    .where(and(eq(orders.publicId, publicId), isNull(orders.stripeCheckoutSessionId)));
}

/* Releasing -------------------------------------------------------------- */

/**
 * Ends a pending order and puts its units back on the shelf, exactly once: the
 * status change and the stock restore are one statement, and the status change
 * only matches a still-pending order. Returns whether this call released it.
 */
export async function releaseOrder(
  publicId: string,
  status: "expired" | "failed",
): Promise<boolean> {
  const result = await db.execute(sql`
    with released as (
      update ${orders}
      set payment_status = ${status}::payment_status, stock_released_at = now(), updated_at = now()
      where public_id = ${publicId} and payment_status = 'pending' and stock_released_at is null
      returning id
    ),
    restored as (
      update ${productStock} as ps
      set quantity = ps.quantity + agg.quantity
      from (
        select product_id, size, sum(quantity)::int as quantity
        from ${orderItems}
        where order_id in (select id from released)
        group by product_id, size
      ) as agg
      where ps.product_id = agg.product_id and ps.size = agg.size
      returning 1
    )
    select count(*)::int as released from released
  `);
  return Number((result.rows[0] as { released: number } | undefined)?.released ?? 0) > 0;
}

/* Paying ----------------------------------------------------------------- */

/** What Stripe says about a paid Checkout Session. Read from Stripe, never from the browser. */
export type PaidDetails = {
  sessionId: string;
  paymentIntentId: string | null;
  currency: string;
  amountSubtotal: number;
  amountShipping: number;
  amountTotal: number;
  email: string | null;
  shippingName: string | null;
  shippingAddress: ShippingAddress | null;
};

export type MarkPaidResult =
  | { outcome: "paid"; stockChanged: boolean }
  | { outcome: "already_paid" }
  | { outcome: "unknown_order" }
  | { outcome: "mismatch" }
  /** Paid after the hold ended and the stock is gone: the caller must refund. */
  | { outcome: "needs_refund" };

async function flagForReview(publicId: string, reason: string) {
  await db
    .update(orders)
    .set({ needsReviewReason: reason })
    .where(and(eq(orders.publicId, publicId), isNull(orders.needsReviewReason)));
}

/**
 * Marks an order paid after Stripe has confirmed the money. The charged amounts
 * must equal what the order was built with, and the update only matches an
 * order that is still pending, so replays and duplicates change nothing.
 */
export async function markPaid(publicId: string, paid: PaidDetails): Promise<MarkPaidResult> {
  const order = await db.query.orders.findFirst({
    where: eq(orders.publicId, publicId),
    with: { items: true },
  });
  if (!order) return { outcome: "unknown_order" };
  if (order.paymentStatus === "paid") return { outcome: "already_paid" };

  const matches =
    (order.stripeCheckoutSessionId === null ||
      order.stripeCheckoutSessionId === paid.sessionId) &&
    paid.currency.toLowerCase() === order.currency &&
    paid.amountSubtotal === order.subtotalCents &&
    paid.amountShipping === order.shippingCents &&
    paid.amountTotal === order.totalCents;
  if (!matches) {
    await flagForReview(publicId, "payment_does_not_match_order");
    return { outcome: "mismatch" };
  }

  const details = {
    paymentStatus: "paid" as const,
    paidAt: new Date(),
    stripeCheckoutSessionId: paid.sessionId,
    stripePaymentIntentId: paid.paymentIntentId,
    email: paid.email,
    shippingName: paid.shippingName,
    shippingAddress: paid.shippingAddress,
  };

  if (order.paymentStatus === "pending") {
    const updated = await db
      .update(orders)
      .set(details)
      .where(and(eq(orders.publicId, publicId), eq(orders.paymentStatus, "pending")))
      .returning({ id: orders.id });
    if (updated.length > 0) return { outcome: "paid", stockChanged: false };

    // Lost a race with another settle of the same order.
    const [now] = await db
      .select({ paymentStatus: orders.paymentStatus })
      .from(orders)
      .where(eq(orders.publicId, publicId));
    if (now?.paymentStatus === "paid") return { outcome: "already_paid" };
    return markPaid(publicId, paid);
  }

  // Paid after the hold ended (expired or failed): take the stock again if it is
  // still there. The check constraint rejects the batch when it is not.
  try {
    await db.batch([
      ...takeStock(stockUse(order.items)),
      db
        .update(orders)
        .set({ ...details, stockReleasedAt: null })
        .where(
          and(
            eq(orders.publicId, publicId),
            inArray(orders.paymentStatus, ["expired", "failed"]),
          ),
        ),
    ] as unknown as Batch);
    return { outcome: "paid", stockChanged: true };
  } catch (error) {
    const { code, constraint } = pgError(error);
    if (code === "23514" && constraint === "product_stock_quantity_non_negative") {
      return { outcome: "needs_refund" };
    }
    throw error;
  }
}

export async function markRefundedForReview(publicId: string, reason: string) {
  await flagForReview(publicId, reason);
}

/* Reading ---------------------------------------------------------------- */

export function getPendingOrder(userId: string) {
  return db.query.orders.findFirst({
    where: and(eq(orders.userId, userId), eq(orders.paymentStatus, "pending")),
    with: { items: true },
  });
}

/** The order for a Checkout Session, only if it belongs to this customer. */
export function getOrderForSession(userId: string, sessionId: string) {
  return db.query.orders.findFirst({
    where: and(
      eq(orders.stripeCheckoutSessionId, sessionId),
      eq(orders.userId, userId),
    ),
    with: { items: true },
  });
}

/** A customer's order history, newest first. Always scoped by `user_id`. */
export function getOrdersForUser(userId: string) {
  return db.query.orders.findMany({
    where: eq(orders.userId, userId),
    columns: {
      publicId: true,
      paymentStatus: true,
      needsReviewReason: true,
      totalCents: true,
      createdAt: true,
    },
    with: { items: { columns: { quantity: true } } },
    orderBy: [desc(orders.createdAt), desc(orders.id)],
  });
}

/** One order by its public id, only if it belongs to this customer. */
export function getOrderForUser(userId: string, publicId: string) {
  return db.query.orders.findFirst({
    where: and(eq(orders.publicId, publicId), eq(orders.userId, userId)),
    with: { items: true },
  });
}

export function getOrderByPublicId(publicId: string) {
  return db.query.orders.findFirst({ where: eq(orders.publicId, publicId) });
}

/** Pending orders whose hold ended before `cutoff`: candidates for reconciling with Stripe. */
export function getStalePendingOrders(cutoff: Date, limit = 50) {
  return db
    .select({
      publicId: orders.publicId,
      stripeCheckoutSessionId: orders.stripeCheckoutSessionId,
    })
    .from(orders)
    .where(and(eq(orders.paymentStatus, "pending"), sql`${orders.reservedUntil} < ${cutoff}`))
    .orderBy(desc(orders.reservedUntil))
    .limit(limit);
}

/* Webhook event log ------------------------------------------------------ */

/**
 * Records an incoming Stripe event. Returns false when it was already fully
 * processed, so a redelivery can be acknowledged without doing the work again.
 * An event that was recorded but not finished is processed again.
 */
export async function claimStripeEvent(id: string, type: string): Promise<boolean> {
  const inserted = await db
    .insert(stripeEvents)
    .values({ id, type })
    .onConflictDoNothing()
    .returning({ id: stripeEvents.id });
  if (inserted.length > 0) return true;

  const [existing] = await db
    .select({ processedAt: stripeEvents.processedAt })
    .from(stripeEvents)
    .where(eq(stripeEvents.id, id));
  return !existing?.processedAt;
}

export async function finishStripeEvent(id: string, orderPublicId: string | null) {
  const order = orderPublicId ? await getOrderByPublicId(orderPublicId) : undefined;
  await db
    .update(stripeEvents)
    .set({ processedAt: new Date(), orderId: order?.id ?? null })
    .where(eq(stripeEvents.id, id));
}
